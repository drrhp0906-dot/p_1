#!/usr/bin/env python3
"""
p_1 · colab/gen_model_fixtures.py — Task 4 parity fixtures
--------------------------------------------------------------------------------
Runs the NumPy transformer (colab/03_model.py) on 4 contract cases and writes:

  docs/model_fixtures.json      the fixture artifact (this is the spec file)
  docs/model_fixtures_data.js   same data as window.P1_MODEL_FIXTURES — the
                                file:// fallback used by docs/model_test.html
                                (browsers block fetch() on file://)

Cases (MODEL seed 42 for the weights, IDS seed 43 fresh per case for tokens):
  1. A_b2_t32  : Config A, B=2, T=32
  2. A_b1_t256 : Config A, B=1, T=256  (full ctx)
  3. A_b3_t8   : Config A, B=3, T=8
  4. B_b2_t64  : Config B, B=2, T=64   (vocab 4096)

Logits are rounded to 5 decimals; the generator asserts the roundtrip error
|logit - round5(logit)| < 1e-4 for EVERY value (would switch to 6 decimals
if the bar were missed — it cannot be, since |round5 err| <= 0.5e-5).

Run:  python3 colab/gen_model_fixtures.py
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from tensor_py import mulberry32                    # noqa: E402
from importlib import import_module                 # noqa: E402

m03 = import_module('03_model')

MODEL_SEED = 42
IDS_SEED = 43
DECIMALS = 5
ROUNDTRIP_BAR = 1e-4


def case_ids(B, T, vocab):
    """Fresh mulberry32(IDS_SEED) per case — same stream the JS side uses."""
    return m03.random_ids(B * T, vocab, IDS_SEED)


def run_case(name, cfg, B, T):
    print('case %s: B=%d T=%d cfg=%s' % (name, B, T, cfg))
    model = m03.Transformer(cfg, seed=MODEL_SEED)
    ids = case_ids(B, T, cfg['vocab_size'])
    logits = model.forward(ids, B)                    # [B*T, vocab]
    V = cfg['vocab_size']
    # roundtrip check BEFORE building nested lists
    max_rt = 0.0
    for v in logits.data:
        r = round(float(v), DECIMALS)
        e = abs(float(v) - r)
        if e > max_rt:
            max_rt = e
    if max_rt >= ROUNDTRIP_BAR:
        raise AssertionError('roundtrip error %.3e >= bar %.1e — use more decimals'
                             % (max_rt, ROUNDTRIP_BAR))
    lg = [[[round(float(logits.data[(b * T + t) * V + j]), DECIMALS)
            for j in range(V)] for t in range(T)] for b in range(B)]
    print('  params=%d  logits max|roundtrip err|=%.1e' % (model.numParams(), max_rt))
    return {
        'name': name,
        'config': dict(cfg),
        'B': B, 'T': T,
        'model_seed': MODEL_SEED,
        'ids_seed': IDS_SEED,
        'num_params': model.numParams(),
        'ids': [ids[b * T:(b + 1) * T] for b in range(B)],
        'logits': lg,
        'roundtrip_max_err': max_rt,
    }


def main():
    cases = [
        run_case('A_b2_t32', m03.CONFIG_A, 2, 32),
        run_case('A_b1_t256', m03.CONFIG_A, 1, 256),
        run_case('A_b3_t8', m03.CONFIG_A, 3, 8),
        run_case('B_b2_t64', m03.CONFIG_B, 2, 64),
    ]
    doc = {
        'format': 'p1-model-fixtures-v1',
        'note': ('Transformer parity fixtures: Python (colab/03_model.py on '
                 'colab/tensor_py.py) forward logits vs the JS twin '
                 '(docs/model.js). Model seed 42, ids seed 43 fresh per case, '
                 'logits rounded to %d decimals (roundtrip bar 1e-4).' % DECIMALS),
        'model_seed': MODEL_SEED,
        'ids_seed': IDS_SEED,
        'rounding_decimals': DECIMALS,
        'parity_bar': 1e-2,
        'cases': cases,
    }

    docs_dir = os.path.join(HERE, '..', 'docs')
    out_json = os.path.join(docs_dir, 'model_fixtures.json')
    out_js = os.path.join(docs_dir, 'model_fixtures_data.js')

    js = json.dumps(doc, separators=(',', ':'))
    with open(out_json, 'w') as f:
        json.dump(doc, f, separators=(',', ':'))
    with open(out_js, 'w') as f:
        f.write('/* AUTO-GENERATED by colab/gen_model_fixtures.py — do not edit.\n'
                '   file:// fallback snapshot of docs/model_fixtures.json\n'
                '   (browsers block fetch() on file://; see tokenizer_data.js). */\n'
                'window.P1_MODEL_FIXTURES = ' + js + ';\n')

    print('wrote %s (%.1f MB)' % (out_json, os.path.getsize(out_json) / 1e6))
    print('wrote %s (%.1f MB)' % (out_js, os.path.getsize(out_js) / 1e6))
    # sanity: JSON roundtrip lossless
    with open(out_json) as f:
        back = json.load(f)
    assert back['format'] == doc['format'] and len(back['cases']) == 4
    print('JSON roundtrip OK · 4 cases · format p1-model-fixtures-v1')
    return 0


if __name__ == '__main__':
    sys.exit(main())
