#!/usr/bin/env node
/* ============================================================================
   p_1 · scripts/test_task4_model.js — Task 4 acceptance gate (Node side)
   ----------------------------------------------------------------------------
   Node mirror of docs/model_test.html (the browser parity page): the pure-JS
   transformer (docs/model.js, built on the docs/tensor.js engine) must
   reproduce the logits that the NumPy twin (colab/tensor_py.py +
   colab/03_model.py) computed for the SAME weights and token ids, on the
   fixture cases in docs/model_fixtures.json (regenerated by
   colab/gen_model_fixtures.py).

   Gate (Task 4 spec): max |Δlogit| < 1e-2 on every case, and the JS param
   count matches the fixture's num_params (wte stored once — weight tying).

   Plus the Task 4 smoke: Config A forward+backward + 10 SGD steps with
   finite-grad / no-NaN asserts (docs/model.js smoke(), the same one the
   browser page runs).

   Run:  node scripts/test_task4_model.js         →  prints ALL TESTS PASSED
   ============================================================================ */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const M = require(path.join(ROOT, 'docs', 'model.js'));

let failures = 0;
const ok = (cond, msg) => { console.log((cond ? '  PASS ' : '  FAIL ') + msg); if (!cond) failures++; return cond; };
const fmt = (...a) => { const s = a[0]; let i = 1; return s.replace(/%[sdg]/g, () => String(a[i++])); };

function main() {
  console.log('p_1 · test_task4_model.js — transformer parity JS vs NumPy fixtures (model v%s)', M.VERSION);

  const fxPath = path.join(ROOT, 'docs', 'model_fixtures.json');
  const fixtures = JSON.parse(fs.readFileSync(fxPath, 'utf8'));
  console.log('  fixtures : %s · %d cases · model_seed %d · ids_seed %d · rounding %d decimals · bar %g'
    .replace('%s', fixtures.format).replace('%d', fixtures.cases.length)
    .replace('%d', fixtures.model_seed).replace('%d', fixtures.ids_seed)
    .replace('%d', fixtures.rounding_decimals).replace('%g', fixtures.parity_bar));

  /* ---------------- TEST 1 — logits parity (JS forward vs Python logits) */
  console.log('\nTEST 1 — logits parity (JS forward vs Python logits)');
  let pass = 0, worst = 0, worstCase = '';
  for (const c of fixtures.cases) {
    const model = new M.Transformer(c.config, c.model_seed);
    const B = c.B, T = c.T, V = c.config.vocab_size;
    const ids = [];
    for (const row of c.ids) for (const t of row) ids.push(t);
    const t0 = Date.now();
    const logits = model.forward(ids, B);
    const ms = Date.now() - t0;
    let maxDiff = 0;
    for (let b = 0; b < B; b++) {
      for (let t = 0; t < T; t++) {
        const row = c.logits[b][t], off = (b * T + t) * V;
        for (let j = 0; j < V; j++) {
          const d = Math.abs(logits.data[off + j] - row[j]);
          if (d > maxDiff) maxDiff = d;
        }
      }
    }
    const good = maxDiff < 1e-2 && model.numParams() === c.num_params;
    if (good) pass++;
    if (maxDiff > worst) { worst = maxDiff; worstCase = c.name; }
    ok(good, fmt('%s max|Δlogit| %s · %d params · %d ms'
      , c.name.padEnd(10), maxDiff.toExponential(3), model.numParams(), ms));
  }
  ok(pass === fixtures.cases.length, fmt('parity %d/%d cases · worst |Δlogit| %s (bar 1e-2)'
    , pass, fixtures.cases.length, worst.toExponential(3) + ' at ' + worstCase));

  /* ------------------------------- TEST 2 — Config A training smoke */
  console.log('\nTEST 2 — Config A training smoke (forward+backward+10 SGD steps)');
  try {
    const res = M.smoke(M.CONFIG_A, 'Config A', (s) => console.log('  | ' + s));
    ok(true, fmt('smoke passed — final loss %s, no NaN', res.loss.toFixed(6)));
  } catch (e) {
    ok(false, 'smoke FAILED — %s', e.message);
  }

  if (failures === 0) {
    console.log('\nALL TESTS PASSED — JS twin reproduces the NumPy logits (worst %s). Tick the box.'
      .replace('%s', worst.toExponential(3)));
    return 0;
  }
  console.log('\nFAILURES: ' + failures);
  return 1;
}

process.exit(main());
