/* ============================================================================
   p_1 · docs/tokenizer.js — byte-level BPE tokenizer (the JavaScript twin)
   ----------------------------------------------------------------------------
   Pure JavaScript, zero dependencies. Runs in the browser (window.P1.BPE) and
   in Node (module.exports). The Python twin is colab/tokenizer_py.py; both
   implement the SAME contract and must agree id-for-id — the acceptance gate
   is scripts/test_task3_tokenizer.js against docs/tokenizer_fixtures.json
   (200 cases generated by the Python twin from corpus/merges.json).

   CONTRACT
     - BYTE-LEVEL BPE. Ids 0..255 = raw UTF-8 bytes (id == byte value). Any
       string encodes regardless of training data: TextEncoder always yields
       bytes, and a byte with no merge available stays a base id.
     - encode(str): str -> UTF-8 bytes -> GPT-2-style rank merging: repeatedly
       find the adjacent pair with the LOWEST merge rank (rank = index in
       merges list; ranks are unique, so no tie-breaking is needed) and merge
       ALL its occurrences left-to-right simultaneously (non-overlapping
       greedy scan); repeat until no adjacent pair is in the table. Never
       emits specials — the caller adds bos/eos.
     - decode(ids): ids -> token bytes (bos/eos -> empty) -> concatenate ->
       TextDecoder('utf-8') which replaces malformed input (never throws).
     - Roundtrip guarantee: decode(encode(s)) == s for any valid UTF-8 string,
       because every merge step is a lossless re-chunking of the byte stream.

   PARITY NOTES (read before touching the merge loop)
     - Everything happens in BYTE domain: TextEncoder().encode(str) produces
       exactly the same bytes as Python str.encode('utf-8') — including for
       astral emoji (surrogate pairs are resolved before bytes exist). Never
       use charCodeAt on the string; it would see UTF-16 code units.
     - The merge loop scans pairs left-to-right and keeps the first lowest
       rank (strict <). Python does the same, so scan order matters — do not
       "optimize" it into a different traversal.
     - Pair keys are exact integers a * 65536 + b (ids < 65536), so Map
       lookups behave like Python tuple lookups, with no string-allocation.

   USAGE
     Browser:  const tok = new P1.BPE(mergesJsonObject);
               const tok = await P1.BPE.fromURL('../corpus/merges.json');
               const ids = tok.encode('hello');   tok.decode(ids);
     Node:     const P1BPE = require('./tokenizer.js');
               const tok = new P1BPE(JSON.parse(fs.readFileSync(path)));
   ============================================================================ */

(function (root, factory) {
  const P1BPE = factory();
  if (typeof module === 'object' && module.exports) module.exports = P1BPE;
  root.P1 = root.P1 || {};
  root.P1.BPE = P1BPE;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';

  const VERSION = '1.0.0';
  const NUM_BASE = 256;        // ids 0..255 = raw bytes
  const KEY_MULT = 65536;      // pair key = a * 65536 + b (exact integer)

  class P1BPE {
    /**
     * @param {object|Array} source  parsed merges.json object
     *   {format, vocab_size, special:{bos,eos}, merges:[[a,b],...]}
     *   — or a raw [[a,b],...] merge list.
     */
    constructor(source) {
      let merges, vocabSize, special;
      if (Array.isArray(source)) {
        merges = source;
        special = {};
        vocabSize = NUM_BASE + merges.length + 2;
      } else if (source && typeof source === 'object' && Array.isArray(source.merges)) {
        merges = source.merges;
        special = source.special || {};
        vocabSize = source.vocab_size || (NUM_BASE + merges.length + 2);
      } else {
        throw new TypeError('P1BPE: pass a parsed merges.json object or a [[a,b],...] merge list');
      }

      this.merges = merges.map(function (p) { return [p[0] | 0, p[1] | 0]; });
      this._rank = new Map();
      for (let k = 0; k < this.merges.length; k++) {
        this._rank.set(this.merges[k][0] * KEY_MULT + this.merges[k][1], k);
      }
      this.vocabSize = vocabSize | 0;
      this.bos = (special.bos !== undefined) ? (special.bos | 0) : this.vocabSize - 2;
      this.eos = (special.eos !== undefined) ? (special.eos | 0) : this.vocabSize - 1;

      // token id -> byte chunk (specials -> empty). Built in merge order, so
      // tb[256+k] = concat(tb[a], tb[b]) always resolves (a, b < 256 + k).
      const tb = new Array(this.vocabSize).fill(null);
      for (let i = 0; i < NUM_BASE; i++) tb[i] = Uint8Array.of(i);
      for (let k = 0; k < this.merges.length; k++) {
        const A = tb[this.merges[k][0]], B = tb[this.merges[k][1]];
        const u = new Uint8Array(A.length + B.length);
        u.set(A); u.set(B, A.length);
        tb[NUM_BASE + k] = u;
      }
      tb[this.bos] = new Uint8Array(0);
      tb[this.eos] = new Uint8Array(0);
      this._tokenBytes = tb;

      this._enc = new TextEncoder();                     // str -> utf8 bytes
      this._dec = new TextDecoder('utf-8');              // bytes -> str (replaces)
    }

    /**
     * GPT-2-style rank-merge. Returns a plain Array of integer ids.
     * NEVER emits specials (ids >= 256 + merges.length).
     */
    encode(str) {
      const bytes = this._enc.encode(str);               // Uint8Array, utf-8
      let ids = new Array(bytes.length);
      for (let i = 0; i < bytes.length; i++) ids[i] = bytes[i];
      const rank = this._rank;
      while (ids.length >= 2) {
        // 1) find the adjacent pair with the lowest merge rank
        let bestRank = -1, bestA = 0, bestB = 0;
        let prev = ids[0];
        for (let i = 1; i < ids.length; i++) {
          const cur = ids[i];
          const r = rank.get(prev * KEY_MULT + cur);
          if (r !== undefined && (bestRank < 0 || r < bestRank)) {
            bestRank = r; bestA = prev; bestB = cur;
          }
          prev = cur;
        }
        if (bestRank < 0) break;                         // no pair in table
        // 2) merge ALL its occurrences left-to-right, non-overlapping
        const a = bestA, b = bestB, m = NUM_BASE + bestRank;
        const out = new Array(ids.length);
        let o = 0, i = 0, n = ids.length;
        while (i < n) {
          if (i < n - 1 && ids[i] === a && ids[i + 1] === b) {
            out[o++] = m; i += 2;
          } else {
            out[o++] = ids[i]; i += 1;
          }
        }
        out.length = o;
        ids = out;
      }
      return ids;
    }

    /** ids -> str. bos/eos decode to nothing; malformed UTF-8 is replaced. */
    decode(ids) {
      const tb = this._tokenBytes;
      let size = 0;
      const chunks = new Array(ids.length);
      let c = 0;
      for (let k = 0; k < ids.length; k++) {
        const t = tb[ids[k]];
        if (t && t.length) { chunks[c++] = t; size += t.length; }
      }
      const buf = new Uint8Array(size);
      let o = 0;
      for (let k = 0; k < c; k++) { buf.set(chunks[k], o); o += chunks[k].length; }
      return this._dec.decode(buf);
    }

    /** Human-readable decoding of a single token (for stats/UI). */
    tokenStr(tokenId) {
      const t = this._tokenBytes[tokenId];
      return t ? this._dec.decode(t) : '';
    }

    /** Number of learned merges (ids 256 .. 256+this-1). */
    get numMerges() { return this.merges.length; }

    /** Browser helper: fetch + parse merges.json, then construct. */
    static fromURL(url) {
      return fetch(url).then(function (r) {
        if (!r.ok) throw new Error('P1BPE.fromURL: HTTP ' + r.status + ' for ' + url);
        return r.json();
      }).then(function (obj) { return new P1BPE(obj); });
    }
  }

  P1BPE.VERSION = VERSION;
  return P1BPE;
});
